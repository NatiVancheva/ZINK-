def add_text(slide, text, x, y, w, h, size=20, color=TEXT, bold=False, align=PP_ALIGN.LEFT):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.margin_left = Inches(.08)
    tf.margin_right = Inches(.08)
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.name = 'Aptos Display'
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.color.rgb = color
    return box


def add_bullets(slide, items, x, y, w, h, size=16, color=TEXT):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame
    tf.clear(); tf.word_wrap = True
    tf.margin_left = Inches(.08)
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = item
        p.level = 0
        p.font.name = 'Aptos'
        p.font.size = Pt(size)
        p.font.color.rgb = color
        p.space_after = Pt(7)
        p.bullet = True
    return box


def add_bg(slide, dark=False):
    fill = slide.background.fill
    fill.solid(); fill.fore_color.rgb = NAVY if dark else LIGHT
    if not dark:
        line = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(.08), Inches(.08), Inches(W-.16), Inches(H-.16))
        line.fill.background(); line.line.color.rgb = BLUE; line.line.width = Pt(1)


def accent(slide, x=.45, y=.45, width=1.25):
    for i, c in enumerate((CYAN, MAGENTA, YELLOW)):
        s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x+i*width/3), Inches(y), Inches(width/3), Inches(.08))
        s.fill.solid(); s.fill.fore_color.rgb = c; s.line.fill.background()


def footer(slide, n, dark=False):
    add_text(slide, f'{n}/66', 12.35, 7.08, .6, .2, 9, WHITE if dark else GRAY, False, PP_ALIGN.RIGHT)


def title(slide, text, dark=False):
    add_text(slide, text, .55, .58, 8.8, .6, 25, WHITE if dark else TEXT, True)
    accent(slide, .55, 1.28, 1.4)


def diagram(slide, label, x=8.8, y=1.8, w=3.8, h=4.25, color=BLUE):
    box = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    box.fill.solid(); box.fill.fore_color.rgb = RGBColor(255,255,255) if slide.background.fill.fore_color.rgb != NAVY else RGBColor(17,45,70)
    box.line.color.rgb = color; box.line.width = Pt(2)
    add_text(slide, label, x+.25, y+h/2-.25, w-.5, .5, 19, color, True, PP_ALIGN.CENTER)
    return box


def add_slide(n, heading, bullets=None, dark=False, visual='Схема'):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_bg(slide, dark); title(slide, heading, dark)
    if bullets: add_bullets(slide, bullets, .65, 1.65, 7.35, 4.9, 16, WHITE if dark else TEXT)
    diagram(slide, visual, 8.55, 1.65, 4.1, 4.55, CYAN if dark else BLUE)
    footer(slide, n, dark)
    return slide

